/** 공백을 모든 조합으로 뺀 꼴(원문 포함) */
function spacings(t: string): string[] {
  const w = t.split(" ");
  const out: string[] = [];
  for (let mask = 0; mask < 1 << (w.length - 1); mask++)
    out.push(w.slice(1).reduce((s, x, i) => s + ((mask >> i) & 1 ? "" : " ") + x, w[0]));
  return out;
}

