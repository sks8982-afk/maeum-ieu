/**
 * 백스톱 판정 — 위급 / 아님 / 모름(오류) 셋으로 가른다.
 *   재확인(맥락 가드가 지운 정규식 L2+, emergency-evaluate)은 '아님'일 때만 내리고 '모름'이면 정규식 판정을 지킨다 —
 *   키 없음·장애·시간 초과·빈 응답·파싱 실패·알 수 없는 분류가 모두 '모름'이다.
 */
export type BackstopVerdict =
  | { kind: "emergency"; result: EmergencyResult }
  | { kind: "none" }
  | { kind: "error" };

/**
 * 발화가 응급/위기 신호인지 LLM으로 판정. 정규식이 L2 미만(none·L1)일 때의 백스톱.
 * @returns 위기로 판정되면 EmergencyResult(level≥2), 아니면 null(아님·모름 모두).
 */
export async function detectEmergencyLLM(userText: string): Promise<EmergencyResult | null> {
  const text = (userText || "").trim();
  if (!text || text.length > 1000) return null;
  if (!SOFT_SIGNAL.test(normalizeForBackstop(text))) return null; // 신호 없음 → LLM 호출 안 함(점·쉼표·'ㅠㅠ'로 띄운 글도 같이 읽는다)
  const v = await askBackstop(text);
  return v.kind === "emergency" ? v.result : null;
}

/**
 * 재확인 — 정규식이 L2+를 찾았지만 맥락 가드(남의 이야기·꿈·TV·지난 일·화투…)가 지운 발화를 백스톱에 다시 묻는다(2026-10-22).
 *   사전필터를 보지 않는다(정규식이 이미 신호를 찾았다). evidence는 정규식 근거(suppressed.evidence)다 — 긴 발화는 그 둘레만 싣는다.
 */
export async function confirmEmergencyLLM(userText: string, evidence = ""): Promise<BackstopVerdict> {
  const text = (userText || "").trim();
  const shown = text ? recheckWindow(text, evidence) : null;
  if (!shown) return { kind: "error" };
  return askBackstop(shown);
}

/** 프롬프트에 싣는 발화 길이 — 비용·지연 상한 */
const BACKSTOP_CHARS = 600;

/**
 * 재확인에 실을 글 — 600자를 넘으면 정규식 근거 둘레를 자른다(2026-10-22 저녁 검토). 예전엔 앞 600자만 실어서
 *   "드라마 이야기 …(600자 넘게)… 근데 지금 갑자기 입이 돌아갔어"의 증상이 프롬프트에 없었고, 백스톱의 '아님'에 L3가 내려갔다.
 *   1000자를 넘으면 묻지도 않고 '모름'(정규식 L3 확정)이라 긴 드라마 이야기가 119 안내가 됐다. 근거를 못 찾으면 null(모름).
 */
function recheckWindow(text: string, evidence: string): string | null {
  if (text.length <= BACKSTOP_CHARS) return text;
  // 근거는 정규식이 읽은 글(normalizeEmergencyText)에서 나왔다 — 같은 글에서 찾는다
  const norm = normalizeEmergencyText(text);
  const at = evidence ? norm.indexOf(evidence) : -1;
  if (at < 0) return null;
  // 맥락 낱말(남의 이야기 주어·TV·지난 일)은 대개 근거 앞에 온다 — 앞쪽을 넉넉히(전언 끝말은 근거 뒤 60자 안)
  const start = Math.max(0, Math.min(at - 400, norm.length - BACKSTOP_CHARS));
  return norm.slice(start, start + BACKSTOP_CHARS);
}

/** 모름 — 운영 로그에 까닭만 남긴다(발화는 남기지 않는다). 재확인에서는 호출부가 정규식 판정을 지킨다 */
function unknownVerdict(why: string): BackstopVerdict {
  console.warn(`[emergency-llm] 백스톱 모름(${why})`);
  return { kind: "error" };
}

async function askBackstop(text: string): Promise<BackstopVerdict> {
  if (!process.env.GEMINI_API_KEY) return unknownVerdict("키 없음");

  // (2026-10-22) [카테고리]의 bleeding을 제 줄로 뗐다. 예전엔 "- fall_injury: 낙상·부상으로 못 일어남. bleeding: 멈추지 않는 출혈."이
  //   한 줄이라 모델이 bleeding을 한 번도 고르지 않았다(실측 출혈 66회 모두 fall_injury). 그래서 맨 "피나요"에 지혈 안내 대신
  //   "움직이지 마시고"가 나갔다(buildEmergencyL3Reply는 카테고리로 안내를 고른다). 낙상과 함께면 fall_injury(정규식 규칙 순서와 같다),
  //   몸속 출혈 신호는 medical_acute(수건 안내가 맞지 않는다), 작은 상처·음식의 피는 none(넓힌 정의가 면도·모기 상처를 L2로 올렸다).
  //   프롬프트를 바꿀 때마다 scripts/eval-backstop-category.ts로 전후를 잰다.
  const prompt = `당신은 노인 돌봄 대화의 안전 분류기입니다. 아래 한 발화가 응급/위기 신호인지 판정하세요. 한국어 사투리·완곡어·우회표현까지 의도 중심으로 해석합니다.

[카테고리]
- suicidal: 자살·자해 의도. 과량복용으로 죽거나 영원히 잠들려는 것, 먼저 떠난 사람 곁으로 가려는 것, 죽으려고 약을 모아두는 것 등 완곡·우회 표현 포함.
- medical_acute: 의식저하·호흡곤란·뇌졸중(한쪽 마비·말 어눌)·급성 심장 증상 등. 피를 토하거나 기침·대변·소변에 피가 섞여 나오는 몸속 출혈 신호(토혈·각혈·혈변·혈뇨·하혈)도 medical_acute.
- medication_error: 실수로 약을 중복/과다 복용한 "완료된 사고". ※복용 여부를 묻는 질문이나 "잘못 먹은 게 아니다" 같은 부정문은 none.
- fall_injury: 넘어짐·미끄러짐·쓰러짐 같은 낙상, 또는 다쳐서 못 일어나거나 못 움직임. 낙상과 함께 피가 나도 fall_injury.
- bleeding: 베이거나 찔리거나 부딪힌 곳에서 피가 나는 위급(피가 난다·흐른다·안 멈춘다·많이 난다, 코피가 안 멈춘다). 낙상 없이 피가 주된 호소면 bleeding — 맨 "피나요"·"피가 나"도 bleeding. 단 긁히거나 살짝 베인 작은 상처의 피(면도·모기 물린 데·딱지 등)는 none — 그래도 피가 안 멈추면 bleeding. 고기·생선 같은 음식의 피나 묻기만 한 피도 none — 본인이 베이거나 다쳤다는 말이 있을 때만 bleeding.
- none: 위 어디에도 아님(평범한 일상·단순 질문·정상 복약 포함).

[레벨] 3=즉시 위기, 2=주의, 0=응급 아님.
판정 원칙: 확실치 않으면 보수적으로 — 진짜 위기를 놓치는 것보다 약하게라도 잡는 게 낫습니다. 단, 단순 복약 질문·부정문·평범한 일상, 그리고 "보고 싶어 죽겠다 / 좋아 죽겠다 / 배고파 죽겠다 / 보고 싶어 죽겠어"처럼 그리움·강조의 관용 표현(실제 자살 의도 아님)은 반드시 none(과잉경보 금지). 먼저 떠난 가족을 그리워하고 보고 싶어하는 것은 애도이지 자살이 아니다(none) — 그 사람을 "따라가겠다/곁으로 가겠다"는 실제 의도가 명시될 때만 suicidal. 자살은 스스로 목숨을 끊으려는 실제 의도가 있을 때만. 또한 "잠깐/가끔/조금/천천히 하면 괜찮은" 정도의 경미하고 일시적인 신체 증상은 none — medical_acute는 갑작스럽고 심하거나 지속되는 경우만(예: "휙 일어나면 잠깐 핑 도는 정도"·"가끔 무릎이 쑤셔"는 응급 아님). 이미 지나가고 해소된 과거 사건("예전에 약을 잘못 먹은 적 있었지, 그 뒤로는 잘 챙겨")은 현재 위기가 아니므로 none. 남의 일을 전해 들은 이야기("…했대·…갔대"), 텔레비전·꿈·반려동물 이야기, 화투(고스톱)의 '피', "다치면 피가 잘 안 멎어" 같은 체질·가정 이야기, 이를 뽑은 뒤 피가 조금 나다 마는 것도 none — 단 지금 곁에 있는 사람(남편·손주 등)이 위급하다는 말이면 그 카테고리.

[발화]
"${text.slice(0, 600)}"

JSON으로만: {"category":"...","level":N,"reason":"간단근거"}`;

  try {
    const res = await getGenAI().models.generateContent({
      model: MODEL,
      contents: prompt,
      config: {
        // ⚠ maxOutputTokens는 thinking + 출력 합산 — thinkingBudget(256)보다 충분히 커야 JSON이 안 잘림
        //   (thinkingBudget 256 + maxOutputTokens 256이면 thinking이 예산을 다 먹어 출력이 잘려 파싱 실패)
        //   예산 256은 ≤3.8 모델에만 실린다. 3.9+·4+·별칭은 thinkingBudget을 400으로 거부하므로 헬퍼가
        //   thinkingLevel "low"로 바꾸는데, 수준은 **토큰 상한이 아니다** — 그 모델로 바꿀 땐 thinking이
        //   1024 안에 들어오는지(=JSON이 안 잘리는지) 실측할 것. 잘리면 파싱 실패 → '모름'이다(사전필터 백스톱은 null,
        //   재확인은 정규식 판정을 지킨다 — 모델이 바뀌어 매번 잘리면 가드에 걸린 이야기가 전부 L3가 된다. 경고 로그를 본다).
        ...geminiTuning(MODEL, { temperature: 0, thinkingBudget: 256, thinkingLevel: "low" }),
        maxOutputTokens: 1024,
        responseMimeType: "application/json",
        responseSchema: SCHEMA,
        safetySettings: COMPANION_SAFETY_SETTINGS, abortSignal: timeoutSignal(LLM_TIMEOUT_MS.emergency),
      },
    });
    logUsage("emergency-llm", res);
    const parsed: unknown = JSON.parse((res.text ?? "").trim());
    // 등급이 숫자가 아니거나 빠졌으면 모름 — 예전엔 0(아님)으로 읽어 재확인이 정규식 L3를 버릴 수 있었다(같은 날 저녁 검토)
    //   배열·숫자·null JSON도 level이 없으니 모름이다(따로 거르지 않는다)
    const raw = (parsed ?? {}) as { category?: unknown; level?: unknown };
    const n = typeof raw.level === "number" ? raw.level : typeof raw.level === "string" && /^\s*\d\s*$/.test(raw.level) ? Number(raw.level) : NaN;
    if (!Number.isFinite(n)) return unknownVerdict("응답 형식");
    const level = Math.max(0, Math.min(3, Math.round(n)));
    if (level < 2) return { kind: "none" };          // none/저신뢰(L2 미만)는 아님
    const category = raw.category as EmergencyCategory;
    if (!VALID.has(category)) return unknownVerdict("모르는 분류"); // L2+인데 모르는 분류 — 판정을 믿을 수 없다
    return { kind: "emergency", result: { level: level as 2 | 3, category, evidence: `llm:${text.slice(0, 40)}` } };
  } catch (e) {
    return unknownVerdict(e instanceof Error ? e.name : "예외"); // 장애·시간 초과(AbortError)·빈 응답·파싱 실패(SyntaxError)
  }
}
