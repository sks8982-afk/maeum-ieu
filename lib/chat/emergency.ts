/**
 * 단일 발화 평가. 과거/비유 맥락이면 강등.
 */
export function detectEmergency(userText: string): EmergencyResult {
  const none: EmergencyResult = { level: 0, evidence: "", category: "none" };
  if (!userText) return none;
  const text = userText.trim();
  if (!text) return none;

  // 과거 회상 / 미디어 / 꿈 — 응급 평가 자체 우회 (단, suicidal/medication은 과거여도 L2로 보존)
  const isPastContext = PAST_CONTEXT_GUARD.test(text);
  // 비유적 표현
  const isFigurative = FIGURATIVE_HINT.test(text);
  // 약 누락 (처방량 미달) — 응급 X
  const isMedicationUnderdose = MEDICATION_UNDERDOSE_GUARD.test(text);
  // 복약 의문/부정 — 음독 응급 아님
  const isMedicationQuestion = MEDICATION_QUESTION_GUARD.test(text) || MEDICATION_CONDITIONAL_GUARD.test(text);

  // 제3자가 겪은 일을 전해 들어 말하는 발화 — 어르신 본인의 응급이 아니므로 알림 대상이 아니다.
  //   L1(관찰)로도 올리지 않는다: 남의 이야기는 본인 건강 추세와 무관하다.
  if (THIRD_PARTY_GUARD.test(text)) return none;

  // L3부터 매칭
  for (const rule of L3_RULES) {
    const m = text.match(rule.pattern);
    if (m) {
      // 약 누락(덜 복용) / 복용 여부 질문·부정 — 응급 X, skip
      if (rule.category === "medication_error" && (isMedicationUnderdose || isMedicationQuestion)) continue;
      // 호흡 비유·증상 부정 — 정규식 L3에서 빼고 백스톱이 문맥으로 판정(위 BREATH_FIGURATIVE 주석, 2026-10-06)
      if (rule.category === "medical_acute") {
        if (/^(?:숨|호흡)/.test(m[0]) && BREATH_FIGURATIVE.test(text)) continue;
        if (/^말/.test(m[0]) && SPEECH_FIGURATIVE.test(text)) continue;
        if (m.index !== undefined && MED_NEGATED.test(text.slice(m.index + m[0].length, m.index + m[0].length + 14))) continue;
      }
      // 과거 회상 — suicidal/medication만 L2로 보존(과소평가 방지), 그 외는 무시
      //   ⚠ 신체 범주는 **근거 바로 앞의 시점 표지**로 판정한다(pastGovernsAt, 2026-10-06 B12) — "어릴 때 다친 적 있는데
      //   지금 어지러워서 못 일어나겠어"가 L0였다. 자살·복약은 따로 조정된 기존(발화 전체) 판정을 유지한다.
      const pastHere = rule.category === "suicidal" || rule.category === "medication_error" || m.index === undefined
        ? isPastContext
        : pastGovernsAt(text, m.index);
      if (pastHere) {
        // 단, 이미 해소된 과거 복약 사고("예전에 ~한 적 있었지, 그 뒤로 잘 챙겨")는 현재 응급 아님 (2026-06-25 라운드7 위양성)
        if (rule.category === "medication_error" && (/적\s*(?:이|도)?\s*있었|그\s*뒤로|그\s*후로?|이제[는요]?\s*(?:잘|괜찮)|인자[는]?\s*(?:잘|괜찮|챙)|지금[은]?\s*(?:잘|괜찮)/.test(text) || /뉴스|드라마|TV|영화|방송|어떤\s*(?:사람|노인|할[머아])/.test(text))) continue;
        // 명백히 해소된 과거 자살사고("젊을 때 죽고 싶었지만 이제는 마음 편해졌어")는 현재 위기 아님 (2026-06-25 라운드17·19)
        //   ⚠ 부정/현재고통 가드 동반 — "지금도 죽고 싶어 마음이 안 편해"(과거틀+현재SI)를 오skip하지 않게.
        //   해소표지는 부정으로 잘 안 깨지는 완료형(편해졌/괜찮아졌/다 지난 일/홀가분 등)만 사용.
        const RESOLVED = /다\s*지난\s*일|편해졌|편안해졌|편안하다|홀가분|마음[\s을를]*놓[았여]|괜찮아졌|나아졌|다\s*나았|좋아졌|이제[는]?[\s가-힣]{0,4}행복|지금[은]?[\s가-힣]{0,4}행복|이제[는]?\s*(?:다\s*)?괜찮아[졌서]/;
        const STILL_DISTRESSED = /지금도|아직도|여전히|요즘|또\s*죽|다시\s*죽|안\s*(?:괜찮|편)|죽고\s*싶어/;
        if (rule.category === "suicidal" && RESOLVED.test(text) && !STILL_DISTRESSED.test(text)) continue;
        /**
         * ⚠ 과거를 언급했다는 이유로 **현재 위기를 강등하지 않는다**(2026-10-02 수정).
         *
         * 결함: "예전에도 그랬는데 **지금도 죽고 싶어**"가 L2로 내려갔다. 과거 맥락 가드가
         *   문장 어딘가의 '예전에'만 보고 전체를 과거 회상으로 처리했기 때문이다.
         *   그 결과 어르신은 109(자살예방상담) 즉답을 **못 받고** L2 힌트만 프롬프트에 섞였다.
         *   만성(과거부터) + 현재 지속은 오히려 고위험 표현인데 가장 약하게 처리된 셈이다.
         *   STILL_DISTRESSED 정규식은 이미 있었지만 RESOLVED 강등을 막는 데만 쓰였고,
         *   L3 복원에는 쓰이지 않았다 — 선언만 되고 절반만 일하던 가드였다.
         * 실측(수정 전): "지금도 죽고 싶어"=L3인데 "예전에도 그랬는데 지금도 죽고 싶어"=L2.
         */
        if (rule.category === "suicidal" && STILL_DISTRESSED.test(text)) {
          return { level: 3, evidence: m[0], category: rule.category };
        }
        if (rule.category === "suicidal" || rule.category === "medication_error") {
          return { level: 2, evidence: m[0], category: rule.category };
        }
        continue;
      }
      // 부정 응답 가드 — 매칭 직후 짧은 창에서 부정이 그 표현에 붙으면 위기 아님 (2026-09-30)
      //   배경: PHQ-9 9번 문항이 "죽고 싶다거나…"를 문항 자체로 제시하므로, 어르신이 **부정으로 답해도**
      //   ("죽고 싶다는 생각은 없었어요") L3로 잡혀 ① 본인 동의 없는 보호자 알림 ② 검진 중단
      //   ③ 9번 점수 미기록이 발생했다. 일상 대화에서도 "죽고 싶다는 생각은 없어"는 위기가 아니다.
      //   ⚠ 창을 12자로 짧게 두고, 현재 고통 표지가 있으면 가드를 적용하지 않아 진짜 신호를 죽이지 않는다.
      //   ⚠ 바른 '못'은 부정 목록에서 제외 — "죽고 싶어도 죽지 못해"는 진짜 신호다.
      if (rule.category === "suicidal" && m.index !== undefined) {
        const after = text.slice(m.index + m[0].length, m.index + m[0].length + 12);
        const NEGATED = /(?:은|는|이|가|도)?\s*없(?:었|어|다|습니|네|고|을)|안\s*(?:해|했|드|들)|아니(?:에|야|다|라|고|)|지\s*않|(?:한|그런)\s*적\s*(?:은|도)?\s*없/;
        // ⚠ 여기엔 '지속'을 뜻하는 표지만 넣는다. 자살 표현 자체(살기 싫다 등)를 넣으면
        //   "살기 싫다는 생각은 없어요" 같은 부정 응답에서 가드가 스스로 무력화된다.
        const STILL_DISTRESSED = /지금도|아직도|여전히|자꾸|계속|또\s*죽|다시\s*죽/;
        if (NEGATED.test(after) && !STILL_DISTRESSED.test(text)) continue;
      }
      // 우회 표현(완곡어) 가드 — 단독으로는 어르신 일상 발화 빈도가 매우 높아 허위 알림의 최대 원인이었다
      //   (2026-10-01 적대 배터리: "병원 예약이라 빨리 가야 해", "이 동네는 살기 싫어",
      //    "그 가방은 짐이 되니까" 가 전부 L3 자살 + 보호자 응급 푸시).
      //   허위 알림이 반복되면 보호자가 경보를 무시하게 되어(경보 피로) 진짜 응급을 놓친다.
      //   → 종결·자기지칭 맥락이 동반될 때만 L3로 인정한다.
      if (rule.category === "suicidal") {
        const ev = m[0];
        // ① 이동 완곡어("빨리/어서/먼저 가야") — 사망·종결 맥락 필수
        const FINALITY = /죽|저\s*세상|하늘나라|영영|하직|따라\s*[가갈]|곁으로|편히\s*[가갈]|눈\s*감|그만\s*살|살\s*맛|살아서\s*[뭐뭣]/;
        if (/^(?:빨리|어서|먼저|얼른)\s*(?:가야|가버려|떠나야|가는\s*게)/.test(ev) && !FINALITY.test(text)) continue;
        // ② 거주·장소 맥락의 "살기 싫다 / 그만 살고 싶다" — 이사·소음 불만이며 자살 아님
        const PLACE_CTX = /(?:여기|이\s*곳|이\s*동네|동네|아파트|이\s*집|시골|도시|서울|층|빌라|주택)[^.!?]{0,14}(?:살기|그만\s*살)|(?:살기|그만\s*살)[^.!?]{0,14}(?:이사|옮기|주택|전세|월세|아파트)/;
        if (/살기\s*(?:가|를)?\s*싫|그만\s*살/.test(ev) && PLACE_CTX.test(text)) continue;
        // ③ "짐이 되다 / 폐를 끼치다" — 자기지칭 필수(사물·제3자 문맥 배제)
        const SELF_REF = /(?:^|[\s,])(?:나|내|저|제)(?:가|는|도|한테|에게|를)?(?=[\s,]|$)|나\s*때문|내\s*때문|괜히\s*나|자식(?:들)?(?:한테|에게)/;
        if (/짐(?:만|이|이만)\s*(?:되|돼)|폐(?:만|를)\s*(?:끼치|끼친|되|돼)/.test(ev) && !SELF_REF.test(text)) continue;
      }
      if (isFigurative && rule.category !== "suicidal" && rule.category !== "medication_error") {
        // 비유 — L2로 강등
        return { level: 2, evidence: m[0], category: rule.category };
      }
      return { level: 3, evidence: m[0], category: rule.category };
    }
  }
  for (const rule of L2_RULES) {
    const m = text.match(rule.pattern);
    if (m) {
      if (m.index !== undefined ? pastGovernsAt(text, m.index) : isPastContext) continue;
      if (isFigurative) return { level: 1, evidence: m[0], category: rule.category };
      return { level: 2, evidence: m[0], category: rule.category };
    }
  }
  for (const rule of L1_RULES) {
    const m = text.match(rule.pattern);
    if (m) {
      if (m.index !== undefined ? pastGovernsAt(text, m.index) : isPastContext) continue;
      return { level: 1, evidence: m[0], category: rule.category };
    }
  }
  return none;
}

import { nameTopic } from "./korean-particle";

/**
 * L3 응답 멘트 — LLM 우회하고 즉시 보내는 안전 안내.
 * companionName의 받침에 따라 조사 자동 선택 (수진이는/수지는).
 */
export function buildEmergencyL3Reply(
  honorific: string,
  companionName: string,
  category: EmergencyCategory,
): string {
  const family = `가족이나 보호자분께 지금 바로 연락해 주세요`;
  const call119 = `${honorific}, 지금 바로 119에 전화해주세요. 손이 떨리시면 119라고 말씀만 하셔도 돼요.`;

  switch (category) {
    case "medical_acute":
      return `${honorific}! 지금 많이 안 좋으신 것 같아요. ${call119} ${family}. ${nameTopic(companionName)} ${honorific} 옆에서 계속 같이 있을게요. 119에 전화하시고 다시 ${companionName} 불러주세요.`;
    case "fall_injury":
      return `${honorific}! 다치셨다니 ${companionName} 너무 놀랐어요. 움직이지 마시고 119에 전화하셔서 도움을 받으세요. ${family}.`;
    case "bleeding":
      return `${honorific}, 피가 멈추지 않으면 위험해요. 깨끗한 수건으로 꾹 눌러주시고, 바로 119에 전화하세요. ${family}.`;
    case "medication_error":
      return `${honorific}, 약을 잘못 드셨다니 큰일이에요. 바로 119에 전화하시고 어떤 약을 얼마나 드셨는지 그대로 말씀해주세요. 토하려 하지 마시고 안내를 기다려주세요.`;
    case "suicidal":
      return `${honorific}, 그런 마음이 드시다니 ${nameTopic(companionName)} 정말 마음이 아파요. 혼자 견디지 마세요. 자살예방상담전화 109번에 지금 바로 전화하시면 24시간 도와주세요. ${family}. ${nameTopic(companionName)} ${honorific} 옆에 계속 있을게요.`;
    default:
      return `${honorific}, 지금 많이 안 좋으신 것 같아요. ${call119} ${family}.`;
  }
}

/**
 * L2 응답 추가 지시 — LLM 프롬프트에 끼워 넣어서 부드러운 권유 강제.
 */
export function buildEmergencyL2Hint(category: EmergencyCategory, evidence: string): string {
  return `\n[응급 신호 감지 — L2 주의 — 매우 중요]
사용자 발화에서 신체 이상 호소가 감지되었습니다 (카테고리: ${category}, 단서: "${evidence}").
다음 규칙을 반드시 지키세요:
- 일상 대화로 흘려보내지 말고, 첫 문장에서 곧바로 상태 확인을 합니다.
- "많이 아프시면 119나 보호자께 꼭 알리세요" 한 줄을 자연스럽게 포함시키세요.
- 사용자가 괜찮다고 해도 한 번 더 부드럽게 권유합니다. 절대 "괜찮으시면 됐어요" 같이 넘어가지 마세요.
- 호칭은 ${"${honorific}"} 그대로, 어조는 평소처럼 따뜻하지만 의지는 분명하게.\n`;
}

/**
 * L1 누적 평가 — 24h 내 L1 신호가 N회↑이면 이번 메시지를 L2로 승격.
 * routeer 단에서 prisma 조회 결과 카운트만 받아 결정.
 */
export function shouldEscalateL1ToL2(recentL1CountIn24h: number): boolean {
  return recentL1CountIn24h >= 3;
}
