/**
 * 띄어쓰기 대신 찍은 점 — "숨을..못..쉬겠어"·"119..불러줘"는 규칙의 창([\s가-힣])이 점을 못 건너 호흡·가슴·119가 통째로 빠졌다
 *   (2026-10-19 독립 검토). 정규식에는 **낱말 사이에 바로 붙은** '..'·'…'만 공백으로 읽는다 — 뒤에 띄어쓰기가 있는
 *   '.. '·'... '와 쉼표는 절 경계일 수 있어 그대로 둔다("어제 넘어졌는데... 일어나서 병원 갔다 왔어"가 L3가 되지 않게).
 *   백스톱 사전필터는 넓게 읽는다(아래 normalizeForBackstop) — 거기서 잘못 열려도 AI가 문맥으로 판정한다.
 */
export function normalizeEmergencyText(text: string): string {
  return text.replace(/(?<=[가-힣0-9])(?:\.{2,}|…+)(?=[가-힣0-9])/g, " ");
}

/**
 * 백스톱 사전필터용 — 한글 사이의 점·줄임표·쉼표·물결·느낌표·'ㅠㅠ'·이모지를 모두 공백으로("숨이ㅠㅠ 안 쉬어져", "숨이.. 안 쉬어져").
 *   (2026-10-21) 점 하나·섞어 쓴 것("숨이.안쉬어져"·"ㅠ.ㅠ"·"ㅠ ㅠ"·"숨이😭안쉬어져")과 쉼표 여러 개도 — 사전필터가 잘못 열려도 AI가 본다.
 *   쉼표는 한글 뒤에서만 — 숫자 자릿점("119,000원")을 '119'로 읽지 않게.
 */
export function normalizeForBackstop(text: string): string {
  return text
    .replace(/(?<=[가-힣0-9])(?:\s*(?:\.+|…+|~+|!+|[ㅠㅜ]+|[\uD800-\uDBFF][\uDC00-\uDFFF]))+\s*(?=[가-힣0-9])/g, " ")
    .replace(/(?<=[가-힣])\s*,+\s*(?=[가-힣0-9])/g, " ");
}

